export const useI18nStore = defineStore('i18n', () => {
    const lang = ref(localStorage.getItem('site_language') || 'zh')

    // 核心：响应式翻译对象 - 所有模板中使用这个
    const currentTranslations = computed(() => {
        return translations[lang.value] || translations.zh
    })

    // 兼容旧写法（返回 computed）
    const t = (key) => {
        return computed(() => translations[lang.value]?.[key] || key)
    }

    // 直接获取翻译值（非响应式，用于 setup 中）
    const get = (key) => {
        return translations[lang.value]?.[key] || key
    }

    const setLang = (newLang) => {
        if (translations[newLang]) {
            lang.value = newLang
            localStorage.setItem('site_language', newLang)
            document.documentElement.lang = newLang
            window.dispatchEvent(new CustomEvent('site:languageChanged', { detail: { lang: newLang } }))
        }
    }

    const getLang = () => lang.value

    return {
        lang,
        currentTranslations,  // 模板中使用：{{ i18n.currentTranslations.brand }}
        t,                    // 模板中使用：{{ i18n.t('brand').value }}
        get,                  // JS 中使用：i18n.get('brand')
        setLang,
        getLang
    }
})